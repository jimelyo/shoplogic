/**
 * Adds/patches i18n keys across all locale files in one atomic operation.
 * The locale files are JSON-compatible nested objects (`const es = {…}`), so
 * this script extracts the object literal, edits it and re-serializes with the
 * same 1-space indent style. Run: node scripts/add-i18n-keys.mjs
 *
 * To use it again in the future, edit the PATCHES object below and run `node scripts/add-i18n-keys.mjs`.
 */
