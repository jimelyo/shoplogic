for (const [lng, keys] of Object.entries(KEYS)) {
  const p = `src/i18n/${lng}.ts`;
  let src = readFileSync(p, 'utf8');
  // Insert right after "vfChainNote" so the fiscal block stays together.
  const anchor = /("vfChainNote"\s*:\s*"[^"]*",\n)/;
  if (!anchor.test(src)) { console.error(`${p}: anchor not found`); process.exit(1); }
  const block = Object.entries(keys).map(([k, v]) => `  "${k}": ${JSON.stringify(v)},`).join('\n');
  src = src.replace(anchor, `$1${block}\n`);
  writeFileSync(p, src);
  console.log(`${lng}: +${Object.keys(keys).length} keys`);
}
